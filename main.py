# НАЧАЛО И ОКОНЧАНИЕ СТРОКИ
# Срез (у строки и у других коллекций, кроме set)
# [начало: окончание: шаг] начало включительно, окончание не включительно
s ='добрый день'

print(s[6]) # сначала и до 5го символа включительно
print(s[7:]) # от 7го индекса и до конца
print(s[3:8]) # от n до m
print(s[::2]) # от начала до конца с шагом 2

